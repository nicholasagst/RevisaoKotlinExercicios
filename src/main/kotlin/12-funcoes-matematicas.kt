import kotlin.math.*// esse asterisco  no final, diz que podemos utilizar todas as funções da biblioteca

fun main() {
    println(max(5,10))//me da o valor máximo entre dois números
    println(min(5,10))//me da o valor minimo entre dois numeros
    println(sqrt(45.67f))//me da araiz quadrada de um número
    println(PI)//apenas o numero pi 3.1415...
    println(E)//sei la o que é euler
    println(round(23323.23131232))//arredonda um numero com virgula
    println()
}